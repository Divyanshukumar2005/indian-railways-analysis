"""Run every query in queries.sql on data/railways.db and save the results.
Writes sql/outputs/<query name>.csv and sql/outputs/RESULTS.md. Run sql/load.py first."""
import re, sqlite3, pandas as pd
from pathlib import Path
HERE = Path(__file__).resolve().parent
con = sqlite3.connect(HERE.parent/"data"/"railways.db")
out = HERE/"outputs"; out.mkdir(exist_ok=True)
text = (HERE/"queries.sql").read_text()
md = ["# SQL results\n", "Generated by `sql/run_queries.py` from `sql/queries.sql`.\n"]
for block in [b.strip() for b in text.split(";") if b.strip()]:
    m = re.search(r"^-- (KPI \d+|Drill-down)[^\n]*", block, re.M)
    if not m:
        continue
    title = m.group(0)[3:]
    sql = "\n".join(l for l in block.splitlines() if not l.startswith("--"))
    df = pd.read_sql_query(sql, con)
    slug = re.sub(r"[^a-z0-9]+", "_", title.lower()).strip("_")[:40]
    df.to_csv(out/f"{slug}.csv", index=False)
    md += [f"\n## {title}\n", df.to_markdown(index=False), "\n"]
    print(title, df.shape)
(out/"RESULTS.md").write_text("\n".join(md))

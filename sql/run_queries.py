"""Run every query in queries.sql on data/railways.db and save the results.

Each query starts with `-- @name <file name>` followed by a `-- <title>` line.
Writes sql/outputs/<name>.csv for every query and sql/outputs/RESULTS.md. Run sql/load.py first.
"""
import re
import sqlite3
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE / "outputs"
OUT.mkdir(exist_ok=True)

# start from a clean folder so a renamed or removed query never leaves a stale file behind
for old in OUT.glob("*.csv"):
    old.unlink()

con = sqlite3.connect(HERE.parent / "data" / "railways.db")
text = (HERE / "queries.sql").read_text()

md = ["# SQL results\n", "Generated by `sql/run_queries.py` from `sql/queries.sql`.\n"]
for block in re.split(r"(?m)^(?=-- @name )", text)[1:]:
    lines = block.strip().splitlines()
    name = lines[0].split("@name", 1)[1].strip()
    title = lines[1].lstrip("- ").strip()
    sql = "\n".join(l for l in lines[1:] if not l.lstrip().startswith("--")).strip().rstrip(";")
    df = pd.read_sql_query(sql, con)
    df.to_csv(OUT / f"{name}.csv", index=False)
    md += [f"\n## {title}\n", df.to_markdown(index=False), "\n"]
    print(f"{name}: {df.shape[0]} rows")

(OUT / "RESULTS.md").write_text("\n".join(md))
con.close()
